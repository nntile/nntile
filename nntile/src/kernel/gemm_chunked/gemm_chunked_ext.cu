#include "gemm_chunked_ext.hh"

#ifdef NNTILE_USE_CUDA

namespace nntile::kernel::gemm_chunked
{

namespace ext
{

// The pieces' three functions, declared at namespace scope (external
// linkage) before the file-private table refers to them.
#define GEMM_CHUNKED_EXT_PIECE(p)                                             \
    int p##_pick(int base, const Call &call) noexcept;                        \
    const char *p##_name(int cfg) noexcept;                                   \
    bool p##_launch(int cfg, const Call &call, cudaStream_t stream) noexcept;
#include "nntile/kernel/gemm_chunked/pieces.inc"
#undef GEMM_CHUNKED_EXT_PIECE

namespace
{

//! Every piece, in file-name order. pieces.inc (generated by the build
//! from the files in ext/) carries one GEMM_CHUNKED_EXT_PIECE(<name>) line
//! per piece; a piece defines <name>_pick, <name>_name and <name>_launch.
struct Piece
{
    PickFn pick;
    NameFn name;
    LaunchFn launch;
};

Piece const kPieces[] = {
#define GEMM_CHUNKED_EXT_PIECE(p) {p##_pick, p##_name, p##_launch},
#include "nntile/kernel/gemm_chunked/pieces.inc"
#undef GEMM_CHUNKED_EXT_PIECE
    {nullptr, nullptr, nullptr},
};

constexpr int kNumPieces = int(sizeof(kPieces) / sizeof(kPieces[0])) - 1;

} // namespace

int pick(const Call &call) noexcept
{
    for (int i = 0; i < kNumPieces; ++i)
    {
        int const cfg = kPieces[i].pick(kFirstCfg + i * kCfgSpan, call);
        if (cfg >= 0)
        {
            return cfg;
        }
    }
    return -1;
}

bool supports(Op ta, Op tb, int m, int n, int k, int batch) noexcept
{
    Call const call{ta,
        tb,
        nullptr,
        0,
        nullptr,
        0,
        nullptr,
        0,
        m,
        n,
        k,
        batch,
        0,
        0,
        0,
        1.f,
        0.f};
    return pick(call) >= 0;
}

const char *name(int cfg) noexcept
{
    int const i = (cfg - kFirstCfg) / kCfgSpan;
    if (cfg < kFirstCfg || i >= kNumPieces)
    {
        return "chunked-ext-?";
    }
    return kPieces[i].name(cfg - kFirstCfg - i * kCfgSpan);
}

bool launch(int cfg, const Call &call, cudaStream_t stream) noexcept
{
    int const i = (cfg - kFirstCfg) / kCfgSpan;
    if (cfg < kFirstCfg || i >= kNumPieces)
    {
        return false;
    }
    return kPieces[i].launch(cfg - kFirstCfg - i * kCfgSpan, call, stream);
}

void *scratch(std::size_t bytes) noexcept
{
    static void *ws = nullptr;
    static std::size_t cap = 0;
    if (bytes > cap)
    {
        void *nw = nullptr;
        if (cudaMalloc(&nw, bytes) == cudaSuccess)
        {
            cudaFree(ws);
            ws = nw;
            cap = bytes;
        }
    }
    return cap >= bytes ? ws : nullptr;
}

} // namespace ext

} // namespace nntile::kernel::gemm_chunked

#endif // NNTILE_USE_CUDA
